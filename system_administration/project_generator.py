import os
import subprocess
from pathlib import Path

class ProjectGenerator:
    @staticmethod
    def create_web_project(project_name: str) -> str:
        try:
            # Erstelle Projektordner auf dem Desktop
            desktop = Path(os.path.expanduser("~")) / "Desktop" / "EVOX_Projects"
            project_path = desktop / project_name
            project_path.mkdir(parents=True, exist_ok=True)
            
            # Erstelle einfache Grundgerüste
            html_content = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>{project_name}</title>
    <link rel="stylesheet" href="style.css">
</head>
<body>
    <h1>Welcome to {project_name}</h1>
    <p>This project was generated by EVOX.</p>
    <script src="script.js"></script>
</body>
</html>"""
            
            css_content = """body { font-family: 'Segoe UI', sans-serif; background: #0B1011; color: #E5EBE5; text-align: center; padding: 50px; }"""
            js_content = """console.log('EVOX Project Loaded');"""
            
            with open(project_path / "index.html", "w", encoding="utf-8") as f:
                f.write(html_content)
            with open(project_path / "style.css", "w", encoding="utf-8") as f:
                f.write(css_content)
            with open(project_path / "script.js", "w", encoding="utf-8") as f:
                f.write(js_content)
                
            # Öffne VS Code in diesem Ordner
            subprocess.Popen(["code", str(project_path)], shell=True)
            
            return f"Success: Created web project at {project_path} and opened it in VS Code."
        except Exception as e:
            return f"Error creating project: {str(e)}"